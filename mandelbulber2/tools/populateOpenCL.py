#!/usr/bin/env python3
#
# Autogenerates OpenCL data structures from the C++ source structures.
#
# This is the Python implementation of tools/populateOpenCL.php. It generates
# both the kernel layout (REAL, selectable with DOUBLE_PRECISION) and the
# host-side single and double layouts used for runtime selectable precision.
#
# usage: tools/populateOpenCL.py [nondry]
#
import os
import re
import sys

PROJECT_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

COPY_FILES = [
	("src/fractal.h", "opencl/fractal_cl.h"),
	("src/fractparams.hpp", "opencl/fractparams_cl.hpp"),
	("src/image_adjustments.h", "opencl/image_adjustments_cl.h"),
	("src/common_params.hpp", "opencl/common_params_cl.hpp"),
	("src/fractal_coloring.hpp", "opencl/fractal_coloring_cl.hpp"),
	("src/texture_enums.hpp", "opencl/texture_enums_cl.h"),
	("src/object_types.hpp", "opencl/object_type_cl.h"),
]

AUTOGEN_LINES = [
	"      ____                   ________ ",
	"     / __ \\____  ___  ____  / ____/ / ",
	"    / / / / __ \\/ _ \\/ __ \\/ /   / /  ",
	"   / /_/ / /_/ /  __/ / / / /___/ /___",
	"   \\____/ .___/\\___/_/ /_/\\____/_____/",
	"       /_/                            ",
	"",
	"This file has been autogenerated by tools/populateOpenCL.py",
	"from the file {source}",
	"D O    N O T    E D I T    T H I S    F I L E !",
]


def read_file(path):
	with open(path, "r", encoding="utf-8") as f:
		return f.read()


def write_file(path, content):
	with open(path, "w", encoding="utf-8", newline="\n") as f:
		f.write(content)


def split_header(content):
	m = re.match(r"/\*\*?[\s\S]*?\*/", content)
	if not m:
		raise RuntimeError("header unknown")
	return m.group(0), content[m.end():]


def add_autogen_header(header, source_name):
	lines = list(AUTOGEN_LINES)
	lines[8] = lines[8].format(source=source_name)
	insertion = " * " + "\n * ".join(lines) + "\n"
	return header[:-2] + insertion + " */"


def remove_namespaces(text):
	"""Remove namespace wrappers but keep their contents, and using namespace."""
	result = []
	i = 0
	pattern = re.compile(r"(?:^|\n)namespace\s+([A-Za-z0-9_]+)\s*\n?\s*\{")
	while True:
		m = pattern.search(text, i)
		if not m:
			result.append(text[i:])
			break
		brace_start = m.end() - 1
		depth = 0
		j = brace_start
		while j < len(text):
			if text[j] == "{":
				depth += 1
			elif text[j] == "}":
				depth -= 1
				if depth == 0:
					break
			j += 1
		if j >= len(text):
			result.append(text[i:])
			break
		prefix = text[i:m.start()]
		leading = "\n" if prefix.startswith("\n") else ""
		if not prefix.startswith("\n"):
			prefix_out = prefix
		else:
			prefix_out = prefix[1:]
		result.append(prefix_out)
		result.append(leading + text[brace_start + 1:j])
		k = j + 1
		if k < len(text) and text[k] == ";":
			k += 1
		while k < len(text) and text[k] in " \t":
			k += 1
		if k < len(text) and text[k] == "\n":
			k += 1
		i = k
	text = "".join(result)
	# drop 'using namespace ...;' statements
	text = re.sub(r"^using namespace\s+[^;]*;\s*\n", "", text, flags=re.M)
	return text


def collect_renames(text):
	names = []
	for m in re.finditer(r"^struct\s+([A-Za-z0-9_]+)\s*$", text, re.M):
		names.append(m.group(1))
	for m in re.finditer(r"^enum\s+([A-Za-z0-9_]+)\s*$", text, re.M):
		names.append(m.group(1))
	for m in re.finditer(r"^const int\s+([A-Za-z0-9_]+)\s*=", text, re.M):
		names.append(m.group(1))
	seen = []
	for name in names:
		if name not in seen:
			seen.append(name)
	return seen


def rename_types(text, names):
	for name in names:
		text = re.sub(r"\b" + re.escape(name) + r"(?=[ \]\(;\n])", name + "Cl", text)
		strip = name[4:] if name.startswith("enum") else name
		if strip:
			strip = strip[0].lower() + strip[1:]
			text = re.sub(re.escape(strip) + "_", strip + "Cl_", text)
	return text


def remove_forward_declarations(text):
	text = re.sub(r"^\s*class\s+[A-Za-z0-9_]+;\s*\n", "", text, flags=re.M)
	text = re.sub(r"^\s*struct\s+[A-Za-z0-9_]+;\s*\n", "", text, flags=re.M)
	text = re.sub(r"^\s*//\s*forward declarations\s*\n", "", text, flags=re.M)
	return text


def remove_includes(text):
	return re.sub(r"^[ \t]*#include[^\n]*\n", "", text, flags=re.M)


def remove_constructors_and_methods(text):
	# empty constructors, e.g. sFractal() {};
	text = re.sub(r"^\s*[A-Za-z0-9_]+\s*\(\)\s*\{\s*\}\s*;?\s*\n", "", text, flags=re.M)
	# constructor declarations with arguments
	text = re.sub(r"^\s*(?:s\w+Cl|s\w+)\s*\([^;]*\)\s*;\s*\n", "", text, flags=re.M)
	# methods that the OpenCL structures do not need
	text = re.sub(r"^\s*void\s+RecalculateFractalParams\s*\([^;]*\)\s*;\s*\n", "", text, flags=re.M)
	text = re.sub(r"^\s*void\s+ApplyNodeData\s*\([^;]*\)\s*;\s*\n", "", text, flags=re.M)
	text = re.sub(r"^\s*double\s+CalculateColorIndex\s*\([\s\S]*?\)\s*;\s*\n", "", text, flags=re.M)
	text = re.sub(
		r"^\s*//\s*Apply common fractal params[\s\S]*?void\s+ApplyNodeData[\s\S]*?;\s*\n",
		"", text, flags=re.M)
	return text


def remove_non_opencl_fields(text):
	text = re.sub(r"^[ \t]*cColorGradient[^\n]*;\s*\n", "", text, flags=re.M)
	text = re.sub(r"^[ \t]*cPrimitives[^\n]*;\s*\n", "", text, flags=re.M)
	return text


def remove_braced_initializers(text):
	return re.sub(r"(\w+(?:\[[^\]]*\])?)\s*\{[^{}\n]*\};", r"\1;", text)


def convert_field_types(text):
	# Structures that live in another generated header are already renamed, so
	# map the nested source names explicitly as well.
	text = re.sub(r"(\s)sCommonParams(\s)", r"\1sCommonParamsCl\2", text)
	text = re.sub(r"(\s)sImageAdjustments(\s)", r"\1sImageAdjustmentsCl\2", text)
	replacements = [
		(r"(\s)int(\s)", r"\1cl_int\2"),
		(r"(\s)bool(\s)", r"\1cl_int\2"),
		(r"(\s)double(\s)", r"\1REAL\2"),
		(r"(\s)float(\s)", r"\1cl_float\2"),
		(r"(\s)sRGB(\s)", r"\1cl_float3\2"),
		(r"(\s)sRGBFloat(\s)", r"\1cl_float3\2"),
		(r"(\s)CVector3(\s)", r"\1REAL3\2"),
		(r"(\s)CVector3", r"\1REAL3"),
		(r"(\s)CVector4(\s)", r"\1REAL4\2"),
		(r"(\s)[a-zA-Z0-9_]+::[a-zA-Z0-9_]+(\s)", r"\1cl_int\2"),
		(r"(\s)CRotationMatrix44(\s)", r"\1matrix44\2"),
		(r"(\s)CRotationMatrix(\s)", r"\1matrix33\2"),
	]
	for pattern, replacement in replacements:
		text = re.sub(pattern, replacement, text)
	# lines that still contain namespace scopes are not supported
	text = re.sub(r"^.*::.*\n", "", text, flags=re.M)
	return text


def wrap_structs_and_enums(text):
	"""Convert struct/enum declarations to the OpenCL typedef form."""
	result = []
	i = 0
	pattern = re.compile(r"(?:^|\n)(struct|enum)\s+([A-Za-z0-9_]+)\s*\n\s*\{")
	while True:
		m = pattern.search(text, i)
		if not m:
			result.append(text[i:])
			break
		kind, name = m.group(1), m.group(2)
		brace_start = text.index("{", m.start())
		depth = 0
		j = brace_start
		while j < len(text):
			if text[j] == "{":
				depth += 1
			elif text[j] == "}":
				depth -= 1
				if depth == 0:
					break
			j += 1
		if j >= len(text):
			result.append(text[i:])
			break
		prefix = text[i:m.start()]
		result.append(prefix + "\n")
		if kind == "struct":
			result.append("typedef struct ALIGN_REAL\n")
		else:
			result.append("typedef enum\n")
		body = text[brace_start + 1:j].strip("\n")
		result.append("{\n" + body + "\n} " + name + ";")
		i = j + 1
		if i < len(text) and text[i] == ";":
			i += 1
	text = "".join(result)
	text = re.sub(r"^const cl_int\s+([A-Za-z0-9_]+)\s*=\s*([A-Za-z0-9_]+);",
		r"#define \1 \2", text, flags=re.M)
	return text


def struct_definitions(text):
	result = []
	pattern = re.compile(r"typedef struct ALIGN_REAL\n\{([\s\S]*?)\n\}\s+([A-Za-z0-9_]+);")
	for m in pattern.finditer(text):
		result.append((m.group(2), m.group(1)))
	return result


def parse_fields(body):
	fields = []
	for raw_line in body.split("\n"):
		line = raw_line.strip()
		if not line or line.startswith("//"):
			continue
		line = line.split("//")[0].strip()
		if not line.endswith(";"):
			continue
		decl = line[:-1].strip()
		if decl.startswith(("typedef ", "struct ", "enum ", "union ")):
			continue
		m = re.match(r"^([A-Za-z0-9_]+)\s+([A-Za-z0-9_]+)(\[[^\]]*\]\s*)*$", decl)
		if not m:
			continue
		type_name = m.group(1)
		rest = decl[len(type_name):].strip()
		name = re.match(r"([A-Za-z0-9_]+)", rest)
		if not name:
			continue
		field_name = name.group(1)
		arrays = re.findall(r"\[([^\]]*)\]", rest)
		fields.append((type_name, field_name, arrays))
	return fields


def source_struct_name(struct_name):
	return struct_name[:-2] if struct_name.endswith("Cl") else struct_name


def helper_name(struct_name, suffix):
	if suffix == "D-promote":
		return "clPromote" + struct_name[0].upper() + struct_name[1:] + "D"
	return "clCopy" + struct_name[0].upper() + struct_name[1:] + suffix


def copy_expression(type_name, dest, mode):
	"""Return the expression used to copy one field.

	mode is 'single' (C++ -> sFooCl), 'double' (C++ -> sFooClD) or
	'promote'/'downcast' between sFooClD and sFooCl.
	"""
	if re.match(r"^s[A-Za-z0-9_]+Cl$", type_name):
		if mode == "single":
			return "clCopy%s(source.%s);" % (type_name[0].upper() + type_name[1:], dest)
		if mode == "double":
			return "clCopy%sD(source.%s);" % (type_name[0].upper() + type_name[1:], dest)
		if mode == "promote":
			return "clPromote%sD(source.%s);" % (type_name[0].upper() + type_name[1:], dest)
		return "clCopy%sSingle(source.%s);" % (type_name[0].upper() + type_name[1:], dest)
	if type_name in ("matrix33", "matrix33D"):
		if mode == "single":
			return "toClMatrix33(source.%s);" % dest
		if mode == "double":
			return "toClMatrix33D(source.%s);" % dest
		if mode == "promote":
			return "toClMatrix33D(source.%s);" % dest
		return "toClFloatMatrix33(source.%s);" % dest
	if type_name in ("matrix44", "matrix44D"):
		if mode == "single":
			return "toClMatrix44(source.%s);" % dest
		if mode == "double":
			return "toClMatrix44D(source.%s);" % dest
		if mode == "promote":
			return "toClMatrix44D(source.%s);" % dest
		return "toClFloatMatrix44(source.%s);" % dest
	if type_name in ("REAL3", "REAL2", "REAL4"):
		if mode == "single":
			return "toClFloat%s(source.%s);" % (type_name[-1], dest)
		return "toClDouble%s(source.%s);" % (type_name[-1], dest)
	if type_name in ("cl_double3", "cl_double2", "cl_double4"):
		if mode == "double" or mode == "promote":
			return "toClDouble%s(source.%s);" % (type_name[-1], dest)
		return "toClFloat%s(source.%s);" % (type_name[-1], dest)
	if type_name in ("cl_float3", "cl_float4", "cl_float2"):
		return "toClFloat%s(source.%s);" % (type_name[-1], dest)
	if re.match(r"^enum[A-Za-z0-9_]+Cl$", type_name):
		return "static_cast<%s>(source.%s);" % (type_name, dest)
	return None


def build_copy_helper(struct_name, fields, mode):
	if mode == "single":
		suffix = ""
		source_type = source_struct_name(struct_name)
		target_type = struct_name
	elif mode == "double":
		suffix = "D"
		source_type = source_struct_name(struct_name)
		target_type = struct_name + "D"
	elif mode == "promote":
		suffix = "D-promote"
		source_type = struct_name
		target_type = struct_name + "D"
	else:
		suffix = "Single"
		source_type = struct_name + "D"
		target_type = struct_name

	out = []
	out.append("inline %s %s(const %s &source)" % (target_type, helper_name(struct_name, suffix), source_type))
	out.append("{")
	out.append("\t%s target;" % target_type)
	for type_name, field_name, arrays in fields:
		prefix = ""
		suffix_braces = ""
		if arrays:
			for index, size in enumerate(arrays):
				v = chr(ord("i") + index)
				prefix += "for(int %s = 0; %s < %s; %s++){" % (v, v, size, v)
			suffix_braces = "}" * len(arrays)
			dest = field_name
			for index in range(len(arrays)):
				dest += "[" + chr(ord("i") + index) + "]"
		else:
			dest = field_name
		expr = copy_expression(type_name, dest, mode)
		if expr is None:
			expr = "source.%s;" % dest
		out.append("\t" + prefix + "target." + dest + " = " + expr + suffix_braces)
	out.append("\treturn target;")
	out.append("}")
	return "\n".join(out)


def transform_d_struct_text(s_text):
	d_text = s_text
	d_text = d_text.replace("typedef struct ALIGN_REAL", "typedef struct ALIGN_DOUBLE")
	d_text = re.sub(r"\bREAL4\b", "cl_double4", d_text)
	d_text = re.sub(r"\bREAL3\b", "cl_double3", d_text)
	d_text = re.sub(r"\bREAL2\b", "cl_double2", d_text)
	d_text = re.sub(r"\bREAL\b", "cl_double", d_text)
	d_text = re.sub(r"\bmatrix33\b", "matrix33D", d_text)
	d_text = re.sub(r"\bmatrix44\b", "matrix44D", d_text)
	d_text = re.sub(r"\bs([A-Za-z0-9_]+)Cl\b", r"s\1ClD", d_text)
	return d_text


def generate_structs_and_helpers(text):
	structs = struct_definitions(text)
	host_helpers = []

	# Kernel-compatible and host double layouts plus their copy methods.
	for name, body in structs:
		s_text = "typedef struct ALIGN_REAL\n{\n" + body.strip("\n") + "\n} " + name + ";"
		d_text = transform_d_struct_text(s_text)
		host_helpers.append(d_text)
		fields = parse_fields(body)
		host_helpers.append(build_copy_helper(name, fields, "double"))
		# The promotion method is used by the dynamic data builders as a fallback
		# for structures which have no direct C++ counterpart.
		host_helpers.append(build_copy_helper(name, fields, "promote"))

	for name, body in structs:
		fields = parse_fields(body)
		host_helpers.append(build_copy_helper(name, fields, "single"))

	helpers = "\n\n".join(host_helpers)
	m = re.search(r"#endif\s*/\*\s*MANDELBULBER2_OPENCL.*", text)
	if m:
		insertion = "\n#ifndef OPENCL_KERNEL_CODE\n" + helpers + "\n#endif /* OPENCL_KERNEL_CODE */\n\n"
		text = text[:m.start()] + insertion + text[m.start():]
	return text


def insert_boolean_operator_enum(text):
	src = os.path.join(PROJECT_PATH, "src/boolean_operator.h")
	if not os.path.exists(src):
		return text
	content = read_file(src)
	m = re.search(r"enum\s+(enumBooleanOperator)\s*\{([\s\S]*?)\};?", content)
	if not m:
		return text
	enum_name = m.group(1) + "Cl"
	body = m.group(2).strip()
	enum_def = "\ntypedef enum\n{\n" + body + "\n} " + enum_name + ";\n\n"
	return re.sub(r"(\} enumTextureMapTypeCl;)", r"\1" + enum_def, text, count=1)


def transform_file(source_path, target_path, source_name):
	raw = read_file(source_path)
	header, body = split_header(raw)
	body = remove_namespaces(body)
	names = collect_renames(body)
	body = rename_types(body, names)
	body = remove_forward_declarations(body)
	body = remove_includes(body)
	body = remove_constructors_and_methods(body)
	body = remove_non_opencl_fields(body)
	body = remove_braced_initializers(body)
	body = convert_field_types(body)
	body = wrap_structs_and_enums(body)

	body = re.sub(r"MANDELBULBER2_SRC_(.*)_HPP_", r"MANDELBULBER2_OPENCL_\1_CL_HPP_", body)
	body = re.sub(r"MANDELBULBER2_SRC_(.*)_H_", r"MANDELBULBER2_OPENCL_\1_CL_H_", body)

	basename = os.path.basename(target_path)
	includes = []
	if basename not in ("common_params_cl.hpp", "fractal_cl.h"):
		includes.append("common_params_cl.hpp")
	if basename != "fractal_cl.h":
		includes.append("fractal_cl.h")
	if basename != "image_adjustments_cl.h":
		includes.append("image_adjustments_cl.h")
	includes.append("opencl_algebra.h")
	cpp_includes = "#ifndef OPENCL_KERNEL_CODE\n"
	cpp_includes += "".join('#include "%s"\n' % x for x in includes)
	cpp_includes += "\n"
	if basename == "fractal_cl.h":
		cpp_includes += '#include "src/include_header_wrapper.hpp"\n'
	cpp_includes += '#include "src/common_params.hpp"\n'
	cpp_includes += '#include "src/fractal.h"\n'
	cpp_includes += '#include "src/fractal_enums.h"\n'
	cpp_includes += '#include "src/fractparams.hpp"\n'
	cpp_includes += '#include "src/image_adjustments.h"\n'
	cpp_includes += "#endif /* OPENCL_KERNEL_CODE */\n"
	body = re.sub(r"(#define MANDELBULBER2_OPENCL_[^\n]*)",
		r"\1\n\n" + cpp_includes, body, count=1)

	if basename == "fractparams_cl.hpp":
		body = insert_boolean_operator_enum(body)

	content = add_autogen_header(header, source_name) + body
	content = generate_structs_and_helpers(content)
	return content


def main():
	dry = not (len(sys.argv) > 1 and sys.argv[1] == "nondry")
	print("RUNNING OPENCL AUTOGENERATION" + (" (dry run)" if dry else ""))
	for source, target in COPY_FILES:
		source_path = os.path.join(PROJECT_PATH, source)
		target_path = os.path.join(PROJECT_PATH, target)
		content = transform_file(source_path, target_path, source)
		old = read_file(target_path) if os.path.exists(target_path) else ""
		if content != old:
			if not dry:
				write_file(target_path, content)
			print("  %s: file changed%s" % (os.path.basename(target_path),
				"" if not dry else " (dry)"))
		else:
			print("  %s: unchanged" % os.path.basename(target_path))
	print("RUNNING OPENCL DEFINE COLLECT")
	print("  defines_cl.h: TODO")


if __name__ == "__main__":
	main()
